SELECT
    DEVICEID AS DEVICE_ID,
    LAT AS LATITUDE,
    LONG AS LONGITUDE,
    TIMESTAMP AS PING_TIMESTAMP,
    LOCATION AS GEO_LOCATION
FROM {{ source('raw', 'gps_pings') }}
WHERE DEVICEID IS NOT NULL
  AND LAT IS NOT NULL
  AND LONG IS NOT NULL
  AND TIMESTAMP IS NOT NULL